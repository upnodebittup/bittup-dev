import {test,expect} from '@playwright/test'
import jwt from 'jsonwebtoken'
test('checkout: preços, quantidades, pedido, PIX, webhook duplicado e interface (mocks)',async({page})=>{
  await page.route('**/api/frete',async route=>{
    const body=route.request().postDataJSON()
    const token=jwt.sign({zip:body.cepDestino,quantity:body.quantidade,price:'5.00',serviceId:1},'synthetic-secret-with-more-than-thirty-two-characters',{algorithm:'HS256',audience:'shipping-quote',expiresIn:'20m'})
    await route.fulfill({json:[{price:'5.00',quoteToken:token}]})
  })
  await page.goto('/loja')
  await page.locator('a[href="/loja/produto/synthetic-product"]').click()
  await page.getByRole('button',{name:'Adicionar ao carrinho'}).click()
  await page.getByRole('button',{name:'Adicionar ao carrinho'}).click()
  await page.goto('/loja/carrinho')
  const cart=await page.evaluate(()=>JSON.parse(localStorage.getItem('loja-roupas-cart')||'[]'))
  expect(cart).toHaveLength(1);expect(cart[0].quantity).toBe(2);expect(cart[0].price).toBe(20)
  await page.goto('/loja/checkout')
  for(const [name,value] of Object.entries({fullName:'Comprador Sintetico',email:'teste@example.invalid',cpf:'00000000000',phone:'11999999999','address.street':'Rua Teste','address.number':'1','address.neighborhood':'Teste','address.city':'São Paulo','address.state':'SP','address.zipCode':'01001000'}))
    await page.locator(`[name="${name}"]`).fill(value)
  const createdPromise=page.waitForResponse(r=>r.url().endsWith('/api/orders')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Finalizar Pedido',exact:true}).click()
  expect((await createdPromise).status()).toBe(200)
  await expect(page).toHaveURL(/synthetic-order\/pagamento/)
  await page.getByRole('button',{name:'Pix Instantâneo',exact:true}).click()
  await page.getByRole('button',{name:'Gerar QR Code PIX',exact:true}).click()
  await expect.poll(async()=>{const r=await page.request.get('/api/orders/synthetic-order');return r.ok()?(await r.json()).customerId:null}).toBe('cus_synthetic')
  const before=await (await page.request.get('/api/orders/synthetic-order')).json()
  expect(Number(before.total)).toBe(40);expect(Number(before.frete)).toBe(5)
  const event={id:'evt_synthetic',event:'PAYMENT_RECEIVED',payment:{id:'pay_synthetic',value:0.01,status:'PENDING'}}
  const send=()=>page.request.post('/api/asaas/webhook',{headers:{'asaas-access-token':'synthetic-webhook-token'},data:event})
  expect((await send()).status()).toBe(200);expect((await send()).status()).toBe(200)
  const after=await (await page.request.get('/api/orders/synthetic-order')).json()
  expect(after.statusPagamento).toBe('approved')
  await page.goto('/loja/pedido/synthetic-order')
  await expect(page.getByText('Pagamento aprovado!',{exact:true})).toBeVisible()
})
